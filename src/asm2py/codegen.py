"""Code generator: turns basic blocks into a runnable Python program."""
from __future__ import annotations

from .ast_nodes import Immediate, Instruction, LabelRef, Register
from .ir import BasicBlock, label_to_block

INDENT = "    "

# Jump opcode -> Python condition
CONDITIONS = {
    "je": "zf",
    "jne": "not zf",
    "jg": "not zf and not sf",
    "jl": "sf",
    "jge": "not sf",
    "jle": "sf or zf",
}

# Opcodes after which control never falls through to the next block
ENDS_FLOW = {"jmp", "ret", "hlt", "call"}


class CodeGenerator:
    """Generates a Python program from a list of basic blocks."""

    def __init__(self, blocks: list[BasicBlock]) -> None:
        self.blocks = blocks
        self.targets = label_to_block(blocks)

    # ---------- public API ----------
    def generate(self) -> str:
        """Return the generated Python source code."""
        first_id = self.blocks[0].id if self.blocks else 0
        instructions = [
            instruction
            for block in self.blocks
            for instruction in block.instructions
        ]
        registers = {
            operand.name.lower()
            for instruction in instructions
            for operand in instruction.operands
            if isinstance(operand, Register)
        }
        if any(instruction.opcode.lower() == "div" for instruction in instructions):
            registers.add("edx")
        has_stack = any(
            instruction.opcode.lower() in {"push", "pop"}
            for instruction in instructions
        )
        has_call_stack = any(
            instruction.opcode.lower() in {"call", "ret"}
            for instruction in instructions
        )
        use_fused_comparisons = self._can_fuse_comparisons()
        lines = ["# Generated by asm2py"]
        lines.extend(f"{register} = 0" for register in ("eax", "ebx", "ecx", "edx") if register in registers)
        if not use_fused_comparisons and any(
            instruction.opcode.lower() == "cmp"
            or instruction.opcode.lower() in CONDITIONS
            for instruction in instructions
        ):
            lines.append("zf = sf = False")
        if has_stack:
            lines.append("stack = []")
        if has_call_stack:
            lines.append("call_stack = []")
        structured_loops = self._structured_loops()
        if structured_loops is not None:
            for index, block in enumerate(self.blocks):
                if index in structured_loops:
                    lines.extend(
                        self._structured_loop_lines(
                            block, use_fused_comparisons
                        )
                    )
                else:
                    lines.extend(self._straight_block_lines(block))
        else:
            lines.extend([f"pc = {first_id}", "while True:"])
            for index, block in enumerate(self.blocks):
                lines.extend(self._block_lines(index, block, use_fused_comparisons))
            lines.append(f"{INDENT}break  # no block matches pc: stop")
        return "\n".join(lines) + "\n"

    # ---------- blocks ----------
    def _next_id(self, index: int) -> int | None:
        """Id of the next block in the LIST (ids may have gaps)."""
        if index + 1 < len(self.blocks):
            return self.blocks[index + 1].id
        return None

    def _block_lines(
        self, index: int, block: BasicBlock, use_fused_comparisons: bool
    ) -> list[str]:
        label = f"  # {block.label}:" if block.label else ""
        lines = [f"{INDENT}if pc == {block.id}:{label}"]
        body: list[str] = []
        instruction_count = len(block.instructions)
        instruction_index = 0
        while instruction_index < instruction_count:
            ins = block.instructions[instruction_index]
            if (
                use_fused_comparisons
                and instruction_index + 1 == instruction_count - 1
                and ins.opcode.lower() == "cmp"
                and block.instructions[instruction_index + 1].opcode.lower() in CONDITIONS
            ):
                body.extend(self._fused_conditional(ins, block.instructions[instruction_index + 1]))
                break
            body.extend(self._instruction(ins))
            instruction_index += 1

        last = block.instructions[-1] if block.instructions else None
        if last is None or last.opcode.lower() not in ENDS_FLOW:
            next_id = self._next_id(index)
            if next_id is None:
                body.append("break")
            else:
                body.append(f"pc = {next_id}")
                body.append("continue")
        if not body:
            body.append("pass")

        lines.extend(f"{INDENT * 2}{line}" for line in body)
        return lines

    def _structured_loops(self) -> dict[int, bool] | None:
        """Find loops that can be represented by sequential Python blocks."""
        if not self.blocks:
            return {}

        loops: dict[int, bool] = {}
        control_flow = set(CONDITIONS) | ENDS_FLOW
        for index, block in enumerate(self.blocks):
            if not block.instructions:
                return None
            last = block.instructions[-1]
            opcode = last.opcode.lower()
            if opcode in CONDITIONS:
                if index == 0 or index + 1 >= len(self.blocks):
                    return None
                target = self._target(last.operands[0])
                next_id = self._next_id(index)
                previous = self.blocks[index - 1]
                previous_last = previous.instructions[-1]
                if (
                    target == block.id
                    and next_id is not None
                    and next_id in block.successors
                    and previous_last.opcode.lower() not in control_flow
                ):
                    loops[index] = True
                    continue
                return None
            if opcode in control_flow:
                if opcode == "hlt" and index == len(self.blocks) - 1:
                    continue
                return None
        return loops

    def _straight_block_lines(self, block: BasicBlock) -> list[str]:
        """Generate a block that falls through to the following block."""
        label = f"  # {block.label}:" if block.label else ""
        lines: list[str] = []
        if label:
            lines.append(label.lstrip())
        instructions = block.instructions
        terminal_comment: str | None = None
        if instructions and instructions[-1].opcode.lower() == "hlt":
            instructions = instructions[:-1]
            terminal_comment = f"# {self._asm_text(block.instructions[-1])}"
        for instruction in instructions:
            lines.extend(self._instruction(instruction))
        if terminal_comment is not None:
            lines.append(terminal_comment)
        if not lines:
            lines.append("pass")
        return lines

    def _structured_loop_lines(
        self, block: BasicBlock, use_fused_comparisons: bool
    ) -> list[str]:
        """Generate a self-loop as a Python ``while`` with a break exit."""
        last = block.instructions[-1]
        lines = ["while True:"]
        body = block.instructions[:-1]
        comparison = body[-1] if body else None
        fused = (
            last.opcode.lower() in CONDITIONS
            and comparison is not None
            and comparison.opcode.lower() == "cmp"
            and use_fused_comparisons
        )
        if fused:
            body = body[:-1]
            for instruction in body:
                lines.extend(
                    f"{INDENT}{line}" for line in self._instruction(instruction)
                )
            condition = self._negated_comparison_condition(comparison, last)
            positive = self._comparison_condition(comparison, last)
            comment = (
                f"  # {self._asm_text(comparison)}; {self._asm_text(last)}"
                f" (if {positive}:)"
            )
            lines.append(f"{INDENT}if {condition}:{comment}")
            lines.append(f"{INDENT * 2}break")
        else:
            for instruction in body:
                lines.extend(
                    f"{INDENT}{line}" for line in self._instruction(instruction)
                )
            if last.opcode.lower() in CONDITIONS:
                lines.append(f"{INDENT}if not ({CONDITIONS[last.opcode.lower()]}):")
                lines.append(f"{INDENT * 2}break  # {self._asm_text(last)}")
            else:
                lines.append(f"{INDENT}continue  # {self._asm_text(last)}")
        if len(lines) == 1:
            lines.append(f"{INDENT}pass")
        return lines

    def _negated_comparison_condition(
        self, comparison: Instruction, jump: Instruction
    ) -> str:
        """Return the direct expression for taking a conditional jump's exit."""
        operators = {
            "je": "!=",
            "jne": "==",
            "jg": "<=",
            "jl": ">=",
            "jge": "<",
            "jle": ">",
        }
        left, right = (
            self._operand(operand) for operand in comparison.operands
        )
        return f"{left} {operators[jump.opcode.lower()]} {right}"

    def _comparison_condition(
        self, comparison: Instruction, jump: Instruction
    ) -> str:
        """Return the direct comparison expression for a fused loop exit."""
        if comparison.opcode.lower() != "cmp":
            raise ValueError("structured conditional loop requires cmp")
        operators = {
            "je": "==",
            "jne": "!=",
            "jg": ">",
            "jl": "<",
            "jge": ">=",
            "jle": "<=",
        }
        left, right = (
            self._operand(operand) for operand in comparison.operands
        )
        return f"{left} {operators[jump.opcode.lower()]} {right}"

    def _can_fuse_comparisons(self) -> bool:
        """Return whether every flag operation has a directly usable comparison."""
        has_comparison_or_jump = False
        for block in self.blocks:
            instructions = block.instructions
            for index, instruction in enumerate(instructions):
                opcode = instruction.opcode.lower()
                if opcode == "cmp" or opcode in CONDITIONS:
                    has_comparison_or_jump = True
                if opcode == "cmp":
                    if (
                        index + 1 >= len(instructions)
                        or instructions[index + 1].opcode.lower() not in CONDITIONS
                    ):
                        return False
                elif opcode in CONDITIONS:
                    if index == 0 or instructions[index - 1].opcode.lower() != "cmp":
                        return False
        return has_comparison_or_jump

    # ---------- operands ----------
    @staticmethod
    def _operand(op: object) -> str:
        if isinstance(op, Register):
            return op.name.lower()
        if isinstance(op, Immediate):
            return str(op.value)
        if isinstance(op, LabelRef):
            return op.name
        raise ValueError(f"unknown operand: {op!r}")

    def _target(self, op: object) -> int:
        assert isinstance(op, LabelRef)
        return self.targets[op.name]

    @classmethod
    def _asm_text(cls, ins: Instruction) -> str:
        ops = ", ".join(cls._operand(o) for o in ins.operands)
        return f"{ins.opcode.lower()} {ops}".strip()

    # ---------- instructions ----------
    def _instruction(self, ins: Instruction) -> list[str]:
        """Return the Python lines for one instruction."""
        op = ins.opcode.lower()
        o = [self._operand(x) for x in ins.operands]
        note = f"  # {self._asm_text(ins)}"

        if op == "mov":
            return [f"{o[0]} = {o[1]}{note}"]
        if op == "add":
            return [f"{o[0]} += {o[1]}{note}"]
        if op == "sub":
            return [f"{o[0]} -= {o[1]}{note}"]
        if op == "mul":
            return [f"{o[0]} *= {o[1]}{note}"]
        if op == "inc":
            return [f"{o[0]} += 1{note}"]
        if op == "dec":
            return [f"{o[0]} -= 1{note}"]
        if op == "cmp":
            return [f"zf = ({o[0]} == {o[1]}){note}", f"sf = ({o[0]} < {o[1]})"]
        if op == "jmp":
            return [f"pc = {self._target(ins.operands[0])}{note}", "continue"]
        if op in CONDITIONS:
            return [
                f"if {CONDITIONS[op]}:{note}",
                f"{INDENT}pc = {self._target(ins.operands[0])}",
                f"{INDENT}continue",
            ]
        if op == "div":
            return [
                f"_d = {o[1]}{note}",
                "if _d == 0:",
                f'{INDENT}raise ZeroDivisionError("division by zero (line {ins.line})")',
                f"edx = {o[0]} % _d",
                f"{o[0]} = {o[0]} // _d",
            ]
        if op == "push":
            return [f"stack.append({o[0]}){note}"]
        if op == "pop":
            return [f"{o[0]} = stack.pop(){note}"]
        if op == "call":
            return_id = self._return_id(ins)
            return [
                f"call_stack.append({return_id}){note}",
                f"pc = {self._target(ins.operands[0])}",
                "continue",
            ]
        if op == "ret":
            return [
                f"if call_stack:{note}",
                f"{INDENT}pc = call_stack.pop()",
                f"{INDENT}continue",
                "break",
            ]
        if op == "print":
            return [f"print({o[0]}){note}"]
        if op == "hlt":
            return [f"break{note}"]
        raise ValueError(f"unknown opcode: {ins.opcode} (line {ins.line})")

    def _fused_conditional(self, comparison: Instruction, jump: Instruction) -> list[str]:
        """Generate a conditional jump directly from a comparison."""
        condition = {
            "je": "==",
            "jne": "!=",
            "jg": ">",
            "jl": "<",
            "jge": ">=",
            "jle": "<=",
        }[jump.opcode.lower()]
        left, right = (self._operand(operand) for operand in comparison.operands)
        comment = f"  # {self._asm_text(comparison)}; {self._asm_text(jump)}"
        return [
            f"if {left} {condition} {right}:{comment}",
            f"{INDENT}pc = {self._target(jump.operands[0])}",
            f"{INDENT}continue",
        ]

    def _return_id(self, ins: Instruction) -> int:
        """Id of the block after the one containing this call (-1 if none)."""
        for index, block in enumerate(self.blocks):
            if block.instructions and block.instructions[-1] is ins:
                next_id = self._next_id(index)
                return -1 if next_id is None else next_id
        return -1