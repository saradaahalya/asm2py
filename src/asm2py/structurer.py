"""Conservative structured Python emitter for assembly programs."""

from __future__ import annotations

from dataclasses import dataclass

from .ast_nodes import Immediate, Instruction, LabelRef, Operand, Program, Register


_CONDITIONS = {
    "je": ("==", "!="),
    "jne": ("!=", "=="),
    "jg": (">", "<="),
    "jl": ("<", ">="),
    "jge": (">=", "<"),
    "jle": ("<=", ">"),
}
_JUMPS = set(_CONDITIONS) | {"jmp"}
_REGISTERS = ("eax", "ebx", "ecx", "edx")
_TERMINATORS = {"hlt", "ret"}


@dataclass
class _Function:
    """A callable assembly region."""

    name: str
    start: int
    end: int


class _Structurer:
    def __init__(self, program: Program) -> None:
        self.program = program
        self.instructions = program.instructions
        self.labels = program.labels
        self.functions: dict[int, _Function] = {}
        self.function_ranges: list[tuple[int, int]] = []

    def structure(self) -> str | None:
        if not self.instructions:
            return "# Generated by asm2py\n"
        if not self._validate_comparisons():
            return None
        if not self._find_functions():
            return None
        if not self._validate_jumps():
            return None

        used = self._used_registers(self.instructions)
        lines = ["# Generated by asm2py"]
        lines.extend(self._register_initializers(used))
        if self._uses_stack(self.instructions):
            lines.append("stack = []")

        for function in self.functions.values():
            lines.extend(self._emit_function(function))
        main_end = self._main_end()
        main, position = self._emit_range(0, main_end, 0, None)
        if position != main_end:
            return None
        lines.extend(main)
        return "\n".join(lines) + "\n"

    def _validate_comparisons(self) -> bool:
        for index, instruction in enumerate(self.instructions):
            opcode = instruction.opcode.lower()
            if opcode == "cmp":
                if index + 1 >= len(self.instructions):
                    return False
                if self.instructions[index + 1].opcode.lower() not in _CONDITIONS:
                    return False
            elif opcode in _CONDITIONS:
                if index == 0 or self.instructions[index - 1].opcode.lower() != "cmp":
                    return False
        return True

    def _find_functions(self) -> bool:
        call_targets = {
            operand.name
            for instruction in self.instructions
            if instruction.opcode.lower() == "call"
            for operand in instruction.operands
            if isinstance(operand, LabelRef)
        }
        for name in call_targets:
            start = self.labels.get(name)
            if start is None or start <= 0:
                return False
            end = start
            while end < len(self.instructions) and self.instructions[end].opcode.lower() != "ret":
                end += 1
            if end >= len(self.instructions):
                return False
            function = _Function(name, start, end + 1)
            self.functions[start] = function
            self.function_ranges.append((start, end + 1))
        for start, end in self.function_ranges:
            for index in range(start, end):
                if self.instructions[index].opcode.lower() == "call":
                    return False
        return True

    def _main_end(self) -> int:
        starts = [start for start, _ in self.function_ranges]
        return min(starts) if starts else len(self.instructions)

    def _validate_jumps(self) -> bool:
        function_ranges = self.function_ranges
        for index, instruction in enumerate(self.instructions):
            opcode = instruction.opcode.lower()
            if opcode not in _JUMPS:
                continue
            target = instruction.operands[0]
            if not isinstance(target, LabelRef) or target.name not in self.labels:
                return False
            target_index = self.labels[target.name]
            in_function = next(
                ((start, end) for start, end in function_ranges if start <= index < end),
                None,
            )
            target_function = next(
                ((start, end) for start, end in function_ranges if start <= target_index < end),
                None,
            )
            if in_function != target_function:
                return False
            if opcode == "call":
                if target_index not in self.functions:
                    return False
            elif opcode == "jmp" and target_index > index:
                return False
        return True

    def _emit_function(self, function: _Function) -> list[str]:
        body, position = self._emit_range(function.start, function.end, 1, function)
        if position != function.end:
            raise _UnsupportedStructure
        assigned = self._assigned_registers(self.instructions[function.start:function.end])
        lines = [f"def {function.name}():"]
        if assigned:
            lines.append("    global " + ", ".join(sorted(assigned)))
        lines.extend(body or ["    pass"])
        return lines

    def _emit_range(
        self, start: int, end: int, level: int, function: _Function | None
    ) -> tuple[list[str], int]:
        lines: list[str] = []
        index = start
        while index < end:
            instruction = self.instructions[index]
            opcode = instruction.opcode.lower()
            loop_end = self._loop_end(index, end)
            if loop_end is not None:
                jump = self.instructions[loop_end]
                body, body_end = self._emit_range(index, loop_end - 1, level + 1, function)
                if body_end != loop_end - 1:
                    return None, index
                lines.append(self._indent(level, "while True:"))
                lines.extend(body)
                if jump.opcode.lower() in _CONDITIONS:
                    comparison = self.instructions[loop_end - 1]
                    left, right = self._comparison_operands(comparison)
                    lines.append(
                        self._indent(
                            level + 1,
                            f"if {left} {self._negated(jump.opcode)} {right}:",
                        )
                    )
                    lines.append(self._indent(level + 2, "break"))
                index = loop_end + 1
                continue
            if opcode in _TERMINATORS:
                if opcode == "ret":
                    return lines, index + 1
                if index == end - 1:
                    return lines, index + 1
                if level > 0:
                    lines.append(self._indent(level, "raise SystemExit"))
                    index += 1
                    continue
                return lines, index + 1

            if opcode == "cmp":
                jump = self.instructions[index + 1]
                target = self._target_index(jump)
                if target <= index:
                    loop_start = target
                    if loop_start < start:
                        return None, index
                    body, body_end = self._emit_range(loop_start, index, level + 1, function)
                    if body_end != index:
                        return None, index
                    lines.append(self._indent(level, "while True:"))
                    lines.extend(body)
                    left, right = self._comparison_operands(instruction)
                    lines.append(
                        self._indent(
                            level + 1,
                            f"if {left} {self._negated(jump.opcode)} {right}:",
                        )
                    )
                    lines.append(self._indent(level + 2, "break"))
                    index += 2
                    continue
                if target > index + 1:
                    true_body, true_end = self._emit_range(target, end, level + 1, function)
                    if true_end == end and self._ends_with_exit(target, end):
                        false_body, false_end = self._emit_range(index + 2, target, level + 1, function)
                        if false_end != target:
                            return None, index
                        left, right = self._comparison_operands(instruction)
                        lines.append(self._indent(level, f"if {left} {self._condition(jump.opcode)} {right}:"))
                        lines.extend(true_body)
                        lines.append(self._indent(level, "else:"))
                        lines.extend(false_body)
                        return lines, end
                return None, index

            if opcode == "call":
                target = self._target_index(instruction)
                if target not in self.functions:
                    return None, index
                lines.append(self._indent(level, f"{self._target_name(instruction)}()  # call {self._target_name(instruction)}"))
                index += 1
                continue
            if opcode in _JUMPS:
                return None, index
            lines.extend(self._emit_instruction(instruction, level))
            index += 1
        return lines, index

    def _loop_end(self, start: int, end: int) -> int | None:
        """Return the jump index for a backward loop beginning at ``start``."""
        for index in range(start + 1, end):
            instruction = self.instructions[index]
            if instruction.opcode.lower() not in {"jmp", * _CONDITIONS}:
                continue
            target = self._target_index(instruction)
            if target == start and index > start:
                if instruction.opcode.lower() in _CONDITIONS:
                    if index == start or self.instructions[index - 1].opcode.lower() != "cmp":
                        return None
                return index
        return None

    def _emit_instruction(self, instruction: Instruction, level: int) -> list[str]:
        opcode = instruction.opcode.lower()
        operands = [self._operand(operand) for operand in instruction.operands]
        comment = f"  # {self._asm_text(instruction)}"
        prefix = " " * (4 * level)
        if opcode == "mov":
            text = f"{operands[0]} = {operands[1]}"
        elif opcode == "add":
            text = f"{operands[0]} += {operands[1]}"
        elif opcode == "sub":
            text = f"{operands[0]} -= {operands[1]}"
        elif opcode == "mul":
            text = f"{operands[0]} *= {operands[1]}"
        elif opcode == "inc":
            text = f"{operands[0]} += 1"
        elif opcode == "dec":
            text = f"{operands[0]} -= 1"
        elif opcode == "print":
            text = f"print({operands[0]})"
        elif opcode == "push":
            text = f"stack.append({operands[0]})"
        elif opcode == "pop":
            text = f"{operands[0]} = stack.pop()"
        elif opcode == "div":
            source, divisor = operands
            return [
                f"{prefix}_d = {divisor}{comment}",
                f"{prefix}if _d == 0:",
                f'{prefix}    raise ZeroDivisionError("division by zero (line {instruction.line})")',
                f"{prefix}edx = {source} % _d",
                f"{prefix}{source} = {source} // _d",
            ]
        else:
            raise _UnsupportedStructure
        return [f"{prefix}{text}{comment}"]

    def _ends_with_exit(self, start: int, end: int) -> bool:
        return any(
            self.instructions[index].opcode.lower() in _TERMINATORS
            for index in range(start, end)
        )

    def _target_index(self, instruction: Instruction) -> int:
        operand = instruction.operands[0]
        if not isinstance(operand, LabelRef):
            raise _UnsupportedStructure
        return self.labels[operand.name]

    def _target_name(self, instruction: Instruction) -> str:
        operand = instruction.operands[0]
        if not isinstance(operand, LabelRef):
            raise _UnsupportedStructure
        return operand.name

    @staticmethod
    def _condition(opcode: str) -> str:
        return _CONDITIONS[opcode][0]

    @staticmethod
    def _negated(opcode: str) -> str:
        return _CONDITIONS[opcode][1]

    def _comparison_operands(self, instruction: Instruction) -> tuple[str, str]:
        return tuple(self._operand(operand) for operand in instruction.operands)  # type: ignore[return-value]

    @staticmethod
    def _operand(operand: Operand) -> str:
        if isinstance(operand, Register):
            return operand.name
        if isinstance(operand, Immediate):
            return str(operand.value)
        if isinstance(operand, LabelRef):
            return operand.name
        raise _UnsupportedStructure

    @classmethod
    def _asm_text(cls, instruction: Instruction) -> str:
        return f"{instruction.opcode} " + ", ".join(
            cls._operand(operand) for operand in instruction.operands
        )

    @staticmethod
    def _used_registers(instructions: list[Instruction]) -> set[str]:
        registers = {
            operand.name
            for instruction in instructions
            for operand in instruction.operands
            if isinstance(operand, Register)
        }
        if any(instruction.opcode.lower() == "div" for instruction in instructions):
            registers.add("edx")
        return registers

    @staticmethod
    def _assigned_registers(instructions: list[Instruction]) -> set[str]:
        assigned: set[str] = set()
        for instruction in instructions:
            if instruction.opcode.lower() in {"mov", "add", "sub", "mul", "inc", "dec", "pop"}:
                if isinstance(instruction.operands[0], Register):
                    assigned.add(instruction.operands[0].name)
            elif instruction.opcode.lower() == "div":
                assigned.update({"eax", "edx"})
        return assigned

    @staticmethod
    def _uses_stack(instructions: list[Instruction]) -> bool:
        return any(instruction.opcode.lower() in {"push", "pop"} for instruction in instructions)

    @staticmethod
    def _register_initializers(registers: set[str]) -> list[str]:
        used = [register for register in _REGISTERS if register in registers]
        return [f"{' = '.join(used)} = 0"] if used else []

    @staticmethod
    def _indent(level: int, text: str) -> str:
        return "    " * level + text


class _UnsupportedStructure(Exception):
    pass


def structure_program(program: Program) -> str | None:
    """Return structured Python for ``program``, or ``None`` if unsupported."""
    try:
        return _Structurer(program).structure()
    except (KeyError, IndexError, TypeError, _UnsupportedStructure):
        return None